import { AlertCircle } from "lucide-react";

import SectionTitle from "../../components/common/SectionTitle";
import ActionButton from "../../components/common/ActionButton";
import Badge from "../../components/common/Badge";
import { useAdminData } from "../../context/AdminDataContext";

const AutomaticMatches = () => {
  const { matches, updateMatch } = useAdminData();

  return (
    <>
      <SectionTitle
        title="Automatic Matches"
        description="Inspect potential matches generated by the matching algorithm."
      />

      <div className="rounded-xl border border-blue-500/20 bg-blue-500/5 p-4 text-sm text-blue-200">
        <div className="flex gap-3">
          <AlertCircle size={19} className="shrink-0" />
          <p>
            Match scores indicate similarity, not proof of ownership. Verify
            ownership through the claims workflow.
          </p>
        </div>
      </div>

      <div className="grid grid-cols-1 gap-4 xl:grid-cols-2">
        {matches.map((match) => (
          <div
            key={match.code}
            className="rounded-2xl border border-[#26303d] bg-[#111720] p-5"
          >
            <div className="flex items-start justify-between gap-3">
              <div className="min-w-0">
                <p className="text-xs text-slate-500">{match.code}</p>
                <h3 className="mt-2 font-semibold text-white">
                  {match.lost} ↔ {match.found}
                </h3>
              </div>
              <Badge>{match.status}</Badge>
            </div>

            <div className="mt-5">
              <div className="mb-2 flex justify-between text-sm">
                <span className="text-slate-400">Similarity score</span>
                <span className="font-semibold text-emerald-400">
                  {match.score}%
                </span>
              </div>
              <div className="h-2 overflow-hidden rounded-full bg-[#26303d]">
                <div
                  className="h-full rounded-full bg-emerald-400"
                  style={{ width: `${match.score}%` }}
                />
              </div>
            </div>

            {match.status === "Suggested" && (
              <div className="mt-5 flex flex-wrap gap-2">
                <ActionButton onClick={() => updateMatch(match.code, "Reviewed")}>
                  Mark reviewed
                </ActionButton>
                <ActionButton danger onClick={() => updateMatch(match.code, "Rejected")}>
                  Reject match
                </ActionButton>
              </div>
            )}
          </div>
        ))}
      </div>

      {matches.length === 0 && (
        <p className="p-10 text-center text-sm text-slate-500">
          No automatic matches yet.
        </p>
      )}
    </>
  );
};

export default AutomaticMatches;